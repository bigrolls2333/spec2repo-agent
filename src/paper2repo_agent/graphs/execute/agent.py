def _should_use_agent_for_task(state: ExecuteGraphState, task: FileGenerationTask) -> bool:
    """Decide whether *task* should be generated by the ReAct agent loop.

    The dispatch policy keeps deterministic files on the template path:
    - task.generation_mode must be ``"llm"`` or ``"hybrid"``.
    - ``PAPER2REPO_EXECUTE_LLM_CODEGEN`` must be enabled.
    - The task must sit at DAG layer ≥ 1 (has upstream dependencies).
    - The task must carry paper-semantic ``plan_fields`` (algorithm core).

    Pure-template files (configs, __init__, README, test_smoke) stay on the
    deterministic template path — they don't benefit from agentic generation
    and the ReAct overhead would only add latency + instability.
    """
    from paper2repo_agent.graphs.execute.nodes import _llm_codegen_enabled

    if task.generation_mode not in {"llm", "hybrid"}:
        return False
    if not _llm_codegen_enabled():
        return False
    depth = task.layer
    has_algo_core = bool(task.plan_fields)
    return depth >= 1 and has_algo_core


