def _safe_repr(value: Any, limit: int = 1000) -> str:
    """Safe, size-bounded repr for tool args/results in agent traces."""
    if value is None:
        return "null"
    if isinstance(value, (int, float, bool)):
        return str(value)
    if isinstance(value, str):
        if len(value) <= limit:
            return value
        return value[:limit] + f"...<truncated {len(value)} chars>"
    import json as _json

    try:
        text = _json.dumps(value, ensure_ascii=False, default=str)
    except (TypeError, ValueError):
        text = str(value)
    if len(text) <= limit:
        return text
    return text[:limit] + f"...<truncated {len(text)} chars>"


