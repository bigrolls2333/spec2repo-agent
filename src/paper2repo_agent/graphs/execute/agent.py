def _stall_warning_message(stall_reason: str | None) -> str:
    """Format the soft-stall warning observation injected into the LLM's context."""
    reason_text = stall_reason or "no progress detected in recent rounds"
    return (
        "## System: Progress Stall Detected\n\n"
        f"Reason: {reason_text}\n\n"
        "You appear to be going in circles. This is your ONE CHANCE to "
        "change approach before the task is terminated. Consider:\n"
        "- Re-reading upstream dependencies — you may have misread an API\n"
        "- Searching for different evidence in the paper\n"
        "- Trying a different implementation strategy entirely\n"
        "- If you believe a plan assumption is wrong, say so explicitly\n\n"
        "If the next round still shows no progress, the task will end "
        "with status 'stall' or 'plan_assumption_invalid'."
    )


# ─────────────────────────────────────────────────────────────────────────
# HITL gate (human interceptor)
# ─────────────────────────────────────────────────────────────────────────


def _hitl_gate(
    state: ExecuteGraphState,
    trace: AgentTrace,
    trigger: str,
    context: dict | None = None,
    fired_set: set | None = None,
) -> str | None:
    """Check whether an in-loop HITL trigger should fire.

    Returns a human-response string to inject as a ``ToolMessage``
    observation, or ``None`` if the trigger is disabled / on cooldown /
    no consult callback is configured.

    The human response is injected into the LLM's message stream so the
    loop continues naturally — **person-as-tool**, not person-as-controller.
    """
    config = state.get("hitl_gate_config")
    if config is None:
        return None

    # Master kill-switch.
    if not getattr(config, "interactive", False):
        return None

    # Individual trigger toggle.
    if not getattr(config, trigger, False):
        return None

    # Cooldown: don't fire the same trigger twice in a single task.
    if fired_set is not None and trigger in fired_set:
        return None

    # Need a consult callback to actually talk to the human.
    consult_fn = state.get("hitl_consult_fn")
    if consult_fn is None:
        return None

    # --- render prompt, consult human, return response ---
    from paper2repo_agent.hitl import render_hitl_trigger_prompt

    prompt = render_hitl_trigger_prompt(trigger, trace, context)
    try:
        response: str | None = consult_fn(trigger, prompt, context)
    except Exception:
        return None

    if not response or not isinstance(response, str) or not response.strip():
        return None

    # Mark as fired for cooldown tracking.
    if fired_set is not None:
        fired_set.add(trigger)

    return (
        f"[Human response to {trigger}]: {response.strip()}\n\n"
        "Use this feedback to adjust your approach in the next round."
    )


# ─────────────────────────────────────────────────────────────────────────
# LLM self-attribution of plan-invalid root cause
# ─────────────────────────────────────────────────────────────────────────


def _llm_attribute_plan_invalid(
    trace: AgentTrace,
    llm: Any,
    state: ExecuteGraphState,
    task: FileGenerationTask,
) -> str | None:
    """Ask the LLM to self-attribute a failure's root cause to a plan assumption.

    Best-effort, non-blocking: returns a ``planning_step_id`` string if the
    LLM identifies a specific plan assumption as the root cause, or ``None``
    if attribution fails or the LLM says it's not a plan fault.

    This augments the keyword heuristic in ``_should_emit_plan_invalid``
    with a semantic attribution pass.
    """
    actions_summary: list[str] = []
    for a in trace.actions[-8:]:
        actions_summary.append(
            f"[{a.action_type}] {a.tool_name or ''}: {_safe_repr(a.reasoning, 200)}"
        )

    from langchain_core.messages import HumanMessage

    attribution_prompt = (
        "You are diagnosing a failed file-generation task. Determine "
        "whether the ROOT CAUSE is a wrong assumption in the original "
        "reproduction plan.\n\n"
        f"Task: {task.path} — {task.purpose}\n"
        f"Plan fields: {', '.join(task.plan_fields) if task.plan_fields else 'none'}\n"
        f"Stall reason: {trace.stall_reason or 'none'}\n\n"
        "Recent agent actions:\n" + "\n".join(actions_summary) + "\n\n"
        "Respond with ONLY a JSON object (no markdown, no extra text):\n"
        '{"is_plan_fault": true|false, "plan_step": "design_tensor_contract"|null, '
        '"explanation": "one short sentence"}'
    )

    try:
        response = llm.invoke([HumanMessage(content=attribution_prompt)])
        text = response.content if isinstance(response.content, str) else str(response.content)
        # Strip markdown code fences if present.
        cleaned = text.strip()
        if cleaned.startswith("```"):
            cleaned = cleaned.removeprefix("```json").removeprefix("```").strip()
            if cleaned.endswith("```"):
                cleaned = cleaned[:-3].strip()
        result = json.loads(cleaned)
        if isinstance(result, dict) and result.get("is_plan_fault") and result.get("plan_step"):
            return str(result["plan_step"])
    except Exception:
        pass
    return None


# ─────────────────────────────────────────────────────────────────────────
# HITL helpers for smoke failures and low-confidence detection
# ─────────────────────────────────────────────────────────────────────────


def _detect_smoke_failure_low_conf(trace: AgentTrace) -> bool:
    """Return True if run_smoke_forward has failed at least twice,
    indicating the LLM has tried to fix but is still failing (low
    effective confidence)."""
    smoke_failures = [
        a
        for a in trace.actions
        if a.action_type == "tool_result"
        and a.tool_name == "run_smoke_forward"
        and a.reasoning
        and '"ok": false' in a.reasoning.lower()
    ]
    return len(smoke_failures) >= 2


def _latest_smoke_error(trace: AgentTrace) -> str:
    """Extract the error message from the most recent failed run_smoke_forward."""
    for a in reversed(trace.actions):
        if a.action_type == "tool_result" and a.tool_name == "run_smoke_forward" and a.reasoning:
            return _safe_repr(a.reasoning, 500)
    return "no smoke error found"


def _last_written_code(state: ExecuteGraphState, trace: AgentTrace) -> str:
    """Return the last code content written via write_repo_file, or empty string."""
    generated = state.get("generated_file_contents", {})
    file_path = trace.file_path
    return generated.get(file_path, "")


# ─────────────────────────────────────────────────────────────────────────
# Fallback bridge — when agent loop fails, degrade to existing single-shot
# ─────────────────────────────────────────────────────────────────────────


def fallback_to_single_shot(
    state: ExecuteGraphState,
    task: FileGenerationTask,
    trace: AgentTrace,
) -> tuple[str, AgentTrace]:
    """Invoke the existing ``_generate_task_file_content`` single-shot path
    when the agent loop terminates in fallback/stall/timeout.

    Returns ``(content, trace)`` so the caller can write the file.
    """
    from paper2repo_agent.graphs.execute.nodes import (
        _generate_task_file_content,
        _render_repo_file,
    )

    progress(
        state,
        f"Agent fallback: {task.path} degraded to single-shot LLM "
        f"(status={trace.final_status}, reason={trace.stall_reason})",
    )
    plan = state["approved_plan"].plan
    spec = state["paper_spec"]
    input_shape = tuple(
        int(x) if isinstance(x, (int, str)) and str(x).isdigit() else None
        for x in (
            spec.model.inputs[0].shape
            if spec.model.inputs and spec.model.inputs[0].shape
            else [None]
        )
    )
    # Guard against empty shape lists — the spec extractor sometimes leaves
    # ``shape: []`` when it cannot infer tensor dims, so indexing [0] would
    # raise IndexError. Fall back to None in that case.
    _output_shape = getattr(spec.model.outputs[0], "shape", None) if spec.model.outputs else None
    num_classes = _output_shape[0] if _output_shape else None
    ctx = {
        "input_shape": input_shape or (None,),
        "num_classes": num_classes,
        "num_samples": plan.data_strategy.synthetic_data_spec.num_samples
        if plan.data_strategy.synthetic_data_spec
        else 8,
        "batch_size": plan.data_strategy.synthetic_data_spec.batch_size
        if plan.data_strategy.synthetic_data_spec
        else 2,
        "learning_rate": spec.training.learning_rate.value or 0.001,
        "task_type": str(spec.task.task_type.value or "classification"),
    }
    baseline = _render_repo_file(task.path, state, ctx)
    content, _context_report, _llm_call, _retrieval = _generate_task_file_content(
        state, task, baseline
    )
    return content, trace


# ─────────────────────────────────────────────────────────────────────────
# Repair agent mode (ReAct loop for diagnosis → fix → verify)
# ─────────────────────────────────────────────────────────────────────────

REPAIR_MAX_STEPS = 6
REPAIR_MAX_TOOL_CALLS = 15
REPAIR_MAX_WALL_SECONDS = 180


def run_file_repair_agent(
    state: ExecuteGraphState,
    file_path: str,
    error_context: str,
    repair_prompt: str | None = None,
) -> AgentTrace:
    """Execute a ReAct loop specialized for repairing a single broken file.

    The agent reads the current file, runs diagnostics, identifies the root
    cause, applies a targeted fix, and verifies the fix works.

    Returns an ``AgentTrace`` whose ``final_status`` indicates success or
    the reason repair failed.
    """
    trace_id = stable_id("repair_agent_trace", file_path, "repair")
    trace = AgentTrace(
        id=trace_id,
        run_id=state["manifest"].run_id,
        task_id=f"repair_{file_path}",
        file_path=file_path,
        actions=[],
        total_steps=0,
        final_status="success",
        created_at=utc_now(),
    )

    executor = ToolExecutor(state)
    settings = Settings.load()
    llm = build_model(settings)
    tools = _build_agent_tools(executor, "repair")
    llm_with_tools = llm.bind_tools(tools) if hasattr(llm, "bind_tools") else llm

    # Read the current file content for context.
    target = state["paths"].generated_repo / file_path
    current_content = ""
    if target.exists():
        current_content = target.read_text(encoding="utf-8", errors="replace")

    messages: list = [
        SystemMessage(content=_build_repair_system_prompt(state, file_path, error_context)),
        HumanMessage(
            content=_build_repair_first_user_message(
                file_path,
                error_context,
                current_content,
                repair_prompt,
            )
        ),
    ]

    step_count = 0
    tool_call_count = 0
    started_wall = time.monotonic()

    try:
        while True:
            step_count += 1
            step_started = time.monotonic()

            response = llm_with_tools.invoke(messages)
            messages.append(response)

            think_action = AgentAction(
                step=step_count,
                action_type="think",
                reasoning=(
                    response.content if isinstance(response.content, str) else str(response.content)
                )[:2000],
                duration_ms=int((time.monotonic() - step_started) * 1000),
            )
            trace.actions.append(think_action)

            # Done signal — check if we've actually written a fix.
            if not getattr(response, "tool_calls", None):
                done_action = AgentAction(
                    step=step_count,
                    action_type="done",
                    reasoning="LLM returned final response with no tool calls.",
                    duration_ms=int((time.monotonic() - step_started) * 1000),
                )
                trace.actions.append(done_action)

                verdict = _latest_verdict(trace)
                if verdict and verdict.get("ok") and _has_write_action(trace):
                    trace.final_status = "success"
                    trace.last_verdict = verdict
                else:
                    trace.final_status = "stall"
                    trace.stall_reason = (
                        "Repair agent declared done but no passing verification found."
                    )
                break

            # Act on tool calls.
            for tc in response.tool_calls:
                tool_call_count += 1
                tc_started = time.monotonic()
                tool_name = tc.get("name", "")
                tool_args = tc.get("args", {})

                try:
                    result = executor.call(tool_name, **tool_args)
                    result_text = _safe_repr(result)
                    tc_status = "succeeded"
                except Exception as exc:
                    result_text = f"Error: {redact_text(str(exc))}"
                    tc_status = "failed"

                tc_duration = int((time.monotonic() - tc_started) * 1000)
                tool_records = state.get("tool_calls", [])
                last_record_id = tool_records[-1].id if tool_records else None

                trace.actions.append(
                    AgentAction(
                        step=step_count,
                        action_type="tool_call",
                        tool_name=tool_name,
                        tool_call_record_id=last_record_id,
                        reasoning=f"Called {tool_name}({_safe_repr(tool_args)}) → status={tc_status}",
                        duration_ms=tc_duration,
                    )
                )
                messages.append(ToolMessage(content=result_text, tool_call_id=tc.get("id", "")))
                trace.actions.append(
                    AgentAction(
                        step=step_count,
                        action_type="tool_result",
                        tool_name=tool_name,
                        tool_call_record_id=last_record_id,
                        reasoning=result_text[:2000],
                        duration_ms=0,
                    )
                )

            # Termination: budget gate.
            wall_elapsed = time.monotonic() - started_wall
            verdict = _latest_verdict(trace)

            if step_count >= REPAIR_MAX_STEPS:
                trace.final_status = "timeout"
                trace.stall_reason = f"Repair budget: steps={step_count}"
                trace.total_steps = step_count
                trace.last_verdict = verdict
                break
            if tool_call_count >= REPAIR_MAX_TOOL_CALLS:
                trace.final_status = "timeout"
                trace.stall_reason = f"Repair budget: tool_calls={tool_call_count}"
                trace.total_steps = step_count
                trace.last_verdict = verdict
                break
            if wall_elapsed >= REPAIR_MAX_WALL_SECONDS:
                trace.final_status = "timeout"
                trace.stall_reason = f"Repair budget: wall={wall_elapsed:.0f}s"
                trace.total_steps = step_count
                trace.last_verdict = verdict
                break

    except Exception as exc:
        trace.final_status = "fallback"
        trace.stall_reason = redact_text(f"{exc.__class__.__name__}: {exc}")
        trace.total_steps = step_count

    trace.total_steps = step_count
    if trace.last_verdict is None:
        trace.last_verdict = _latest_verdict(trace)
    return trace


def _build_repair_system_prompt(
    state: ExecuteGraphState,
    file_path: str,
    error_context: str,
) -> str:
    """Build system prompt for the repair agent."""
    package = state["execution_policy"].package_name
    return (
        "You are a careful code repair agent. Your task is to diagnose and fix "
        "a verification failure in a paper reproduction repository. The named "
        "file is an initial lead, not a claim that it is the root cause.\n\n"
        "Method:\n"
        "1. Start from the failure and form a concrete root-cause hypothesis.\n"
        "2. Investigate only the relevant provider, consumer, test, contract, or "
        "paper evidence. Prefer API summaries and code search before full files.\n"
        "3. Decide which side of a cross-file boundary is inconsistent. Preserve "
        "the approved design, public API coherence, and paper semantics.\n"
        "4. Apply a MINIMAL targeted patch to whichever related file(s) are wrong.\n"
        "5. Run the cheapest verification that can falsify the hypothesis. If it "
        "passes, run the relevant broader contract/runtime verification.\n"
        "6. If verification exposes a new error, revise the hypothesis instead of "
        "repeating the same action.\n\n"
        "Rules:\n"
        "- Make the smallest possible change that fixes the issue.\n"
        "- Do NOT assume the initially named file is the only file that may be changed.\n"
        "- Do NOT rewrite an entire file when a localized patch is sufficient.\n"
        "- Do not delete or weaken tests, skip verification, swallow exceptions, "
        "or replace required behavior with constants/stubs merely to pass.\n"
        "- If you cannot fix after 3 attempts, explain why the issue may be "
        "a plan assumption rather than a code bug.\n"
        "- Keep imports safe — do not add network or system calls.\n\n"
        f"Target file: {file_path}\n"
        f"Package: {package}\n"
        f"Initial error context:\n{error_context[:4000]}"
    )


def _build_repair_first_user_message(
    file_path: str,
    error_context: str,
    current_content: str,
    repair_prompt: str | None,
) -> str:
    """Build the first user message for the repair agent."""
    prompt_part = repair_prompt or "Diagnose and fix the issue."
    content_preview = current_content[:5000] if current_content else "(file does not exist)"
    return (
        f"Repair the file `{file_path}`.\n\n"
        f"Error context from verification:\n{error_context[:2000]}\n\n"
        f"Repair hint:\n{prompt_part}\n\n"
        f"Current file content:\n```python\n{content_preview}\n```\n\n"
        "Use this preview as the initial working set. Do not re-read it in full "
        "unless the missing portion is relevant. Search/read related files on "
        "demand, state a root-cause hypothesis, apply a minimal fix, and verify it."
    )
