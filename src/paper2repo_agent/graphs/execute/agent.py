def _latest_verdict(trace: AgentTrace) -> dict | None:
    """Extract the most recent objective verification result from actions.

    Looks for ``run_smoke_forward`` or ``check_python_syntax`` tool_result
    actions and returns the first parseable dict found, scanning backwards.
    """
    for action in reversed(trace.actions):
        if action.action_type != "tool_result":
            continue
        if action.tool_name not in {
            "run_smoke_forward",
            "check_python_syntax",
            "check_file_contract",
        }:
            continue
        if action.reasoning:
            # Try to parse as JSON for structured verdict
            import json as _json

            try:
                parsed = _json.loads(action.reasoning)
                if isinstance(parsed, dict):
                    # Verification tools use different, but equivalent,
                    # success keys.  Normalize them here so the repair loop
                    # does not treat a passing contract/syntax/import check as
                    # an inconclusive verdict.
                    if "ok" not in parsed:
                        for key in ("passed", "valid", "success"):
                            if key in parsed:
                                parsed["ok"] = bool(parsed[key])
                                break
                    parsed.setdefault("source", action.tool_name)
                    return parsed
            except (_json.JSONDecodeError, TypeError):
                # Tool results are currently recorded through ``_safe_repr``,
                # which produces a Python-literal dict rather than JSON.
                # Parse that representation safely before falling back to
                # string markers.
                try:
                    import ast as _ast

                    parsed = _ast.literal_eval(action.reasoning)
                    if isinstance(parsed, dict):
                        if "ok" not in parsed:
                            for key in ("passed", "valid", "success"):
                                if key in parsed:
                                    parsed["ok"] = bool(parsed[key])
                                    break
                        parsed.setdefault("source", action.tool_name)
                        return parsed
                except (ValueError, SyntaxError, TypeError):
                    pass
            # Fallback: scan for ok/error markers
            lowered = action.reasoning.lower()
            if '"ok": true' in lowered or '"ok":true' in lowered:
                return {"ok": True, "source": action.tool_name}
            if '"ok": false' in lowered or '"ok":false' in lowered:
                return {"ok": False, "source": action.tool_name}
    return None


def _detect_progress_window(actions: list[AgentAction], window: int = 3) -> tuple[bool, str | None]:
    """Layer 1 — soft-signal stall detection.

    Returns ``(is_stalling, reason)`` by checking whether the last *window*
    tool-call actions are repeating (same tool + same args signature → cycle)
    or whether observe results show no new information.
    """
    tool_actions = [a for a in actions if a.action_type == "tool_call"]
    if len(tool_actions) < window:
        return False, None

    recent = tool_actions[-window:]
    # Cycle detection: same tool name repeated N times.
    names = {a.tool_name for a in recent}
    if len(names) == 1:
        return True, f"cyclic_calls: {next(iter(names))} called {window}×"

    # No-progress detection: last N tool_results are effectively identical.
    result_actions = [a for a in actions if a.action_type == "tool_result"]
    if len(result_actions) >= window:
        recent_results = result_actions[-window:]
        fingerprints = {
            sha256_text((r.tool_name or "") + (r.reasoning or "")[:200])[:12]
            for r in recent_results
        }
        if len(fingerprints) == 1:
            return True, "no_new_info"

    return False, None


def _should_emit_plan_invalid(trace: AgentTrace, verdict: dict | None) -> str | None:
    """Layer 4 — decide whether a failure's root cause points to a plan
    assumption.

    Returns the ``planning_step_id`` to invalidate, or ``None``.
    """
    if verdict and verdict.get("ok"):
        return None
    # Heuristic: if the trace contains run_smoke_forward failures with
    # shape/dimension keywords, it likely points to a tensor-contract
    # assumption in the plan.
    for action in reversed(trace.actions):
        if action.action_type != "tool_result":
            continue
        if action.tool_name != "run_smoke_forward":
            continue
        reasoning = (action.reasoning or "").lower()
        if any(
            kw in reasoning
            for kw in [
                "shape",
                "dimension",
                "broadcast",
                "mat1 and mat2",
                "size mismatch",
                "matmul",
            ]
        ):
            return "design_tensor_contract"
    return None


def _terminate_decision(
    *,
    trace: AgentTrace,
    step_count: int,
    tool_call_count: int,
    wall_elapsed: float,
    verdict: dict | None,
) -> Literal["continue", "timeout", "plan_assumption_invalid"]:
    """Budget-gate termination with plan-invalid upgrade (Layer 2 + 4).

    Layer 1 (stall soft-warn / hard-stop) is handled directly in the
    ReAct loop.  Layer 3 (success) is handled in the no-tool_calls path.
    This function only guards the hard budget limits.
    """
    # Layer 2 — budget gate.
    if step_count >= DEFAULT_MAX_STEPS:
        plan_step = _should_emit_plan_invalid(trace, verdict)
        return "plan_assumption_invalid" if plan_step else "timeout"
    if tool_call_count >= DEFAULT_MAX_TOOL_CALLS:
        plan_step = _should_emit_plan_invalid(trace, verdict)
        return "plan_assumption_invalid" if plan_step else "timeout"
    if wall_elapsed >= DEFAULT_MAX_WALL_SECONDS:
        return "timeout"

    return "continue"


def _has_write_action(trace: AgentTrace) -> bool:
    """True if the trace contains at least one successful repository write."""
    return any(
        a.action_type == "tool_call"
        and a.tool_name in {"write_repo_file", "write_repo_files_batch"}
        and "succeeded" in (a.reasoning or "")
        for a in trace.actions
    )


