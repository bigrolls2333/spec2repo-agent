# ReAct agent loop
# ─────────────────────────────────────────────────────────────────────────

# Budget constants (tunable per-run later via ExecutionPolicy).
DEFAULT_MAX_STEPS = 8
DEFAULT_MAX_TOOL_CALLS = 20
DEFAULT_MAX_WALL_SECONDS = 300  # 5 min — aligns with build_model timeout


def run_file_generation_agent(
    state: ExecuteGraphState,
    task: FileGenerationTask,
) -> AgentTrace:
    """Execute the think→act→observe ReAct loop for a single file task.

    Returns an ``AgentTrace`` whose ``final_status`` is one of the five
    terminal states: success / stall / timeout / plan_assumption_invalid /
    fallback.
    """
    trace_id = stable_id("agent_trace", task.id, task.path)
    trace = AgentTrace(
        id=trace_id,
        run_id=state["manifest"].run_id,
        task_id=task.id,
        file_path=task.path,
        actions=[],
        total_steps=0,
        final_status="success",
        created_at=utc_now(),
    )

    executor = ToolExecutor(state)
    settings = Settings.load()
    llm = build_model(settings)
    tools = _build_agent_tools(executor, state.get("execution_phase", "generation"))
    llm_with_tools = llm.bind_tools(tools) if hasattr(llm, "bind_tools") else llm

    messages: list = [
        SystemMessage(content=_build_agent_system_prompt(state, task)),
        HumanMessage(content=_build_agent_first_user_message(state, task)),
    ]

    step_count = 0
    tool_call_count = 0
    started_wall = time.monotonic()
    hitl_fired: set[str] = set()

    # Stall soft-warn: give the LLM one more round before the hard stop.
    stall_warning_issued = False
    # Track which HITL triggers have fired during this loop.
    try:
        while True:
            step_count += 1
            step_started = time.monotonic()

            # ── think ────────────────────────────────────────────────
            response = llm_with_tools.invoke(messages)
            messages.append(response)

            think_action = AgentAction(
                step=step_count,
                action_type="think",
                reasoning=(
                    response.content if isinstance(response.content, str) else str(response.content)
                )[:2000],
                duration_ms=int((time.monotonic() - step_started) * 1000),
            )
            trace.actions.append(think_action)

            # ── done signal (no tool calls) ──────────────────────────
            if not getattr(response, "tool_calls", None):
                done_action = AgentAction(
                    step=step_count,
                    action_type="done",
                    reasoning="LLM returned final response with no tool calls.",
                    duration_ms=int((time.monotonic() - step_started) * 1000),
                )
                trace.actions.append(done_action)

                # done-pinned-to-verdict: only accept "done" when a
                # verification round passed AND a file was written.
                verdict = _latest_verdict(trace)
                if verdict and verdict.get("ok") and _has_write_action(trace):
                    trace.final_status = "success"
                    trace.last_verdict = verdict
                else:
                    trace.final_status = "stall"
                    trace.stall_reason = (
                        "LLM declared done but no passing verification "
                        "signal found in preceding actions."
                    )
                break

            # ── HITL T4: before critical write ───────────────────────
            for tc in response.tool_calls:
                if tc.get("name") == "write_repo_file":
                    hitl_resp = _hitl_gate(
                        state,
                        trace,
                        "before_critical_write",
                        {"tool_name": tc.get("name", ""), "tool_args": tc.get("args", {})},
                        hitl_fired,
                    )
                    if hitl_resp:
                        messages.append(
                            ToolMessage(
                                content=hitl_resp,
                                tool_call_id="hitl_before_critical_write",
                            )
                        )
                        trace.actions.append(
                            AgentAction(
                                step=step_count,
                                action_type="think",
                                reasoning=f"HITL before_critical_write: {hitl_resp[:200]}",
                                duration_ms=0,
                            )
                        )

            # ── act (tool calls) ─────────────────────────────────────
            for tc in response.tool_calls:
                tool_call_count += 1
                tc_started = time.monotonic()
                tool_name = tc.get("name", "")
                tool_args = tc.get("args", {})

                # ── execute via shared ToolExecutor底座 ──────────
                try:
                    result = executor.call(tool_name, **tool_args)
                    result_text = _safe_repr(result)
                    tc_status = "succeeded"
                except Exception as exc:  # noqa: BLE001
                    result_text = f"Error: {redact_text(str(exc))}"
                    tc_status = "failed"

                tc_duration = int((time.monotonic() - tc_started) * 1000)

                # Find the ToolCallRecord that executor.call just wrote.
                tool_records = state.get("tool_calls", [])
                last_record_id = tool_records[-1].id if tool_records else None

                tool_call_action = AgentAction(
                    step=step_count,
                    action_type="tool_call",
                    tool_name=tool_name,
                    tool_call_record_id=last_record_id,
                    reasoning=f"Called {tool_name}({_safe_repr(tool_args)}) → status={tc_status}",
                    duration_ms=tc_duration,
                )
                trace.actions.append(tool_call_action)

                # ── observe (result back to LLM) ──────────────────
                messages.append(ToolMessage(content=result_text, tool_call_id=tc.get("id", "")))
                tool_result_action = AgentAction(
                    step=step_count,
                    action_type="tool_result",
                    tool_name=tool_name,
                    tool_call_record_id=last_record_id,
                    reasoning=result_text[:2000],
                    duration_ms=0,
                )
                trace.actions.append(tool_result_action)

            # ── HITL T2: smoke failure + low confidence ──────────────
            if _detect_smoke_failure_low_conf(trace):
                hitl_resp = _hitl_gate(
                    state,
                    trace,
                    "on_smoke_failure_low_conf",
                    {
                        "error_info": _latest_smoke_error(trace),
                        "last_code": _last_written_code(state, trace),
                    },
                    hitl_fired,
                )
                if hitl_resp:
                    messages.append(
                        ToolMessage(
                            content=hitl_resp,
                            tool_call_id="hitl_smoke_failure",
                        )
                    )
                    trace.actions.append(
                        AgentAction(
                            step=step_count,
                            action_type="think",
                            reasoning=f"HITL on_smoke_failure_low_conf: {hitl_resp[:200]}",
                            duration_ms=0,
                        )
                    )

            # ── termination check ────────────────────────────────────
            verdict = _latest_verdict(trace)
            wall_elapsed = time.monotonic() - started_wall

            # Layer 1 — soft-signal stall detection.
            is_stalling, stall_reason = _detect_progress_window(trace.actions)
            if is_stalling:
                if not stall_warning_issued:
                    # ── HITL T1: on_stall ──────────────────────────
                    hitl_resp = _hitl_gate(
                        state,
                        trace,
                        "on_stall",
                        {"stall_reason": stall_reason},
                        hitl_fired,
                    )
                    if hitl_resp:
                        messages.append(
                            ToolMessage(
                                content=hitl_resp,
                                tool_call_id="hitl_on_stall",
                            )
                        )
                        trace.actions.append(
                            AgentAction(
                                step=step_count,
                                action_type="think",
                                reasoning=f"HITL on_stall: {hitl_resp[:200]}",
                                duration_ms=0,
                            )
                        )

                    # Inject soft-warn observation — one more chance.
                    messages.append(
                        ToolMessage(
                            content=_stall_warning_message(stall_reason),
                            tool_call_id="system_stall_warning",
                        )
                    )
                    stall_warning_issued = True
                    trace.actions.append(
                        AgentAction(
                            step=step_count,
                            action_type="think",
                            reasoning=f"Stall warning issued: {stall_reason}",
                            duration_ms=0,
                        )
                    )
                    continue  # ← give LLM one more round

                else:
                    # Second consecutive stall → hard stop.
                    plan_step = _should_emit_plan_invalid(trace, verdict)
                    if plan_step:
                        # HITL T3 + T5: before_plan_invalid / falsified
                        for trig, ctx in [
                            (
                                "before_plan_invalid",
                                {
                                    "plan_step": plan_step,
                                    "reason": f"stall repeated: {stall_reason}",
                                },
                            ),
                            ("on_plan_assumption_falsified", {"plan_step": plan_step}),
                        ]:
                            hitl_resp = _hitl_gate(
                                state,
                                trace,
                                trig,
                                ctx,
                                hitl_fired,
                            )
                            if hitl_resp:
                                messages.append(
                                    ToolMessage(
                                        content=hitl_resp,
                                        tool_call_id=f"hitl_{trig}",
                                    )
                                )
                        trace.final_status = "plan_assumption_invalid"
                        trace.invalidated_planning_step_id = plan_step
                    else:
                        trace.final_status = "stall"
                    trace.stall_reason = stall_reason or "stall detected after warning"
                    trace.total_steps = step_count
                    trace.last_verdict = verdict
                    break
            else:
                # Progress detected — reset stall warning.
                stall_warning_issued = False

            # Layer 2 — budget gate.
            decision = _terminate_decision(
                trace=trace,
                step_count=step_count,
                tool_call_count=tool_call_count,
                wall_elapsed=wall_elapsed,
                verdict=verdict,
            )

            if decision != "continue":
                trace.total_steps = step_count
                if decision == "timeout":
                    trace.final_status = "timeout"
                    trace.stall_reason = (
                        f"budget exceeded: steps={step_count}, "
                        f"tool_calls={tool_call_count}, "
                        f"wall={wall_elapsed:.0f}s"
                    )
                elif decision == "plan_assumption_invalid":
                    # Try LLM self-attribution for better accuracy.
                    plan_step = _should_emit_plan_invalid(trace, verdict)
                    if plan_step is None:
                        plan_step = _llm_attribute_plan_invalid(trace, llm, state, task)
                    # HITL T3 + T5.
                    for trig, ctx in [
                        (
                            "before_plan_invalid",
                            {
                                "plan_step": plan_step or "unknown",
                                "reason": f"budget exceeded: steps={step_count}",
                            },
                        ),
                        ("on_plan_assumption_falsified", {"plan_step": plan_step or "unknown"}),
                    ]:
                        hitl_resp = _hitl_gate(
                            state,
                            trace,
                            trig,
                            ctx,
                            hitl_fired,
                        )
                        if hitl_resp:
                            messages.append(
                                ToolMessage(
                                    content=hitl_resp,
                                    tool_call_id=f"hitl_{trig}",
                                )
                            )
                    trace.final_status = "plan_assumption_invalid"
                    trace.invalidated_planning_step_id = plan_step
                trace.last_verdict = verdict
                break

    except Exception as exc:  # noqa: BLE001
        trace.final_status = "fallback"
        trace.stall_reason = redact_text(f"{exc.__class__.__name__}: {exc}")
        trace.total_steps = step_count

    trace.total_steps = step_count
    if trace.last_verdict is None:
        trace.last_verdict = _latest_verdict(trace)
    return trace


