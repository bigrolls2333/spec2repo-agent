def _build_agent_system_prompt(state: ExecuteGraphState, task: FileGenerationTask) -> str:
    """Construct the system prompt that defines the agent's role and rules."""
    package = state["execution_policy"].package_name
    deps_text = _render_generated_dependencies(state, task.path)
    contract_text = (
        "\n".join(f"- {item}" for item in task.contract)
        if task.contract
        else "(no structured contract)"
    )

    return (
        "You are a careful coding agent generating one file for a paper "
        "reproduction repository. You work in a think→act→observe loop: "
        "you may call tools to read dependencies, search paper evidence, "
        "check syntax, run smoke tests, and write the final file.\n\n"
        "Rules:\n"
        "1. Read upstream dependencies FIRST (use read_generated_file with "
        "mode='api_summary') to see their real public signatures before "
        "writing any code.\n"
        "2. Search paper evidence when uncertain about algorithm details.\n"
        "3. After writing code, run check_python_syntax. If it passes, run "
        "run_smoke_forward to verify tensor shapes at runtime.\n"
        "4. If run_smoke_forward reports a shape mismatch or error, "
        "diagnose it, fix the code, and re-verify. Do NOT declare done "
        "until verification passes.\n"
        "5. If you cannot fix the issue after 3 attempts, explain why and "
        "which plan assumption may be wrong — this will trigger a "
        "plan-level review.\n\n"
        f"Target file: {task.path}\n"
        f"Package: {package}\n"
        f"Purpose: {task.purpose}\n\n"
        f"Required contract symbols:\n{contract_text}\n\n"
        "Already-generated dependencies (INTERFACE CONTRACT — use ONLY "
        "these exact names and signatures):\n\n"
        f"{deps_text[:8000]}\n\n"
        "Your final action must be write_repo_file with the complete, "
        "verified file content."
    )


def _build_agent_first_user_message(state: ExecuteGraphState, task: FileGenerationTask) -> str:
    """The first user message that kicks off the ReAct loop."""
    plan_fields_str = ", ".join(task.plan_fields) if task.plan_fields else "(none)"
    evidence_ids = (
        ", ".join(task.relevant_evidence_ids[:10]) if task.relevant_evidence_ids else "(none)"
    )
    planning_trace_context = _render_agent_planning_trace_context(state)
    coding_plan = state.get("coding_plan")
    code_context = (
        _code_implementation_context_for_file(coding_plan, task.path)
        if coding_plan is not None
        else {}
    )
    code_context_text = (
        json.dumps(code_context, ensure_ascii=False, indent=2) if code_context else "{}"
    )
    return (
        f"Generate the file `{task.path}`.\n\n"
        f"Purpose: {task.purpose}\n"
        f"Plan fields to implement: {plan_fields_str}\n"
        f"Relevant evidence IDs: {evidence_ids}\n\n"
        "CodeImplementationPlan context for this file. Treat the interfaces "
        "inside it as the paper-specific source of truth; generic smoke or "
        "classification APIs are fallback only when the CodeImplementationPlan "
        "does not define a primary interface:\n"
        f"{code_context_text}\n\n"
        "Current planning hypotheses:\n"
        f"{planning_trace_context}\n\n"
        "Start by reading any upstream dependency files whose APIs you "
        "need, then search for relevant paper evidence, then write and "
        "verify the code. Do not write the file until you have checked "
        "the dependencies."
    )


def _render_agent_planning_trace_context(state: ExecuteGraphState) -> str:
    planning_trace = state.get("planning_trace")
    if planning_trace is None:
        return "- none"
    lines = [
        f"- trace_id={planning_trace.id}",
        f"- rollback_iteration={int(state.get('rollback_count', 0) or 0)}",
    ]
    revisions = state.get("plan_trace_revisions", []) or []
    if revisions:
        latest = revisions[-1]
        lines.append(f"- latest_revision={latest.id}: {latest.revision_rationale}")
    for step in planning_trace.steps[:12]:
        lines.append(
            f"- {step.step_id} [{step.reasoning_type}] "
            f"hypothesis={step.hypothesis}; falsifiable_via={step.falsifiable_via}"
        )
    return "\n".join(lines)


def _build_agent_tools(executor: ToolExecutor, phase: str) -> list:
    """Return the list of LangChain StructuredTools visible to the LLM
    for *phase*.

    Calls ``_agent_visible_tools`` + ``to_langchain_tool`` factories from
    ``tools.py``.
    """
    from paper2repo_agent.graphs.execute.tools import (
        _agent_visible_tools,
        to_langchain_tool,
    )

    visible_specs = _agent_visible_tools(executor.specs, phase)
    return [to_langchain_tool(spec, executor) for spec in visible_specs]


