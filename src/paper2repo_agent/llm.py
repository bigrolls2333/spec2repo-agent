def build_model(settings: Settings) -> ChatOpenAI:
    settings.require_llm()
    return ChatOpenAI(
        model=settings.model_name,
        api_key=settings.openai_api_key,
        base_url=settings.openai_base_url,
        temperature=settings.llm_temperature,
        # File-level code generation (model/losses/train) emits hundreds of
        # lines in one shot; large provider responses can exceed a short read
        # timeout, which silently falls back to the empty baseline template and
        # guts the paper-specific code. Raise the ceiling and lean on more
        # transport-level retries so a slow response is re-attempted instead of
        # degrading to a stub.
        timeout=300,
        max_retries=4,
    )


def extract_json_value(text: str) -> Any:
    """Extract a JSON object or array from a possibly fenced LLM response."""
    stripped = text.strip()
    if stripped:
        try:
            return json.loads(stripped)
        except json.JSONDecodeError:
            pass
    fenced = re.search(r"```(?:json)?\s*(.*?)\s*```", text, re.DOTALL)
    if fenced:
        fenced_payload = fenced.group(1).strip()
        try:
            return json.loads(fenced_payload)
        except json.JSONDecodeError:
            pass
    candidates: list[tuple[int, str]] = []
    for opener, closer in (("{", "}"), ("[", "]")):
        start = text.find(opener)
        end = text.rfind(closer)
        if start >= 0 and end > start:
            candidates.append((start, text[start : end + 1]))
    for _, candidate in sorted(candidates, key=lambda item: item[0]):
        try:
            return json.loads(candidate)
        except json.JSONDecodeError:
            continue
    raise ValueError("LLM response did not contain a JSON object or array")


def extract_json(text: str) -> dict:
    payload = extract_json_value(text)
    if isinstance(payload, dict):
        return payload
    raise ValueError("LLM response did not contain a JSON object")


def extract_spec_with_llm(
    parsed: ParsedPaper,
    evidence_ids: list[str],
    settings: Settings,
    *,
    fake_llm: bool = False,
    progress: Callable[[str], None] | None = None,
) -> PaperSpec:
    if fake_llm:
        if progress:
            progress("LLM: using deterministic fake PaperSpec")
        return fake_paper_spec(parsed, evidence_ids)

    if progress:
        progress(f"LLM: invoking {settings.model_name} for PaperSpec extraction")
    model = build_model(settings)
    example_evidence_id = evidence_ids[0] if evidence_ids else None
    schema_hint = {
        "id": "<backend-owned; may be omitted>",
        "metadata": {
            "title": {
                "value": "paper title",
                "value_type": "str",
                "source_type": "paper",
                "evidence_ids": [example_evidence_id] if example_evidence_id else [],
                "confidence": 0.8,
                "notes": None,
            }
        },
        "task": {},
        "model": {},
        "datasets": [],
        "training": {},
        "evaluation": {},
        "dependencies": {},
        "implementation_notes": [],
        "claims_to_reproduce": [],
        "extraction_gaps": [],
        "source_policy_ref": None,
    }
    system = SystemMessage(
        content=(
            "You extract implementation specifications from machine learning papers. "
            "Return only a JSON object matching the requested shape. "
            "Follow the field contract, few-shot example, and identifier rules exactly. "
            "Use only backend-provided evidence IDs. Keep missing fields as null ExtractedField values."
        )
    )
    payload: dict[str, Any] = {}
    for part_name, fields, keywords in _paper_spec_extraction_parts():
        part_evidence_ids, context = _paper_spec_part_context(
            parsed,
            evidence_ids,
            keywords,
        )
        part_shape = {
            key: schema_hint.get(
                key,
                {}
                if key
                not in {
                    "datasets",
                    "implementation_notes",
                    "claims_to_reproduce",
                    "extraction_gaps",
                }
                else [],
            )
            for key in fields
        }
        user = HumanMessage(
            content=(
                f"Extract ONLY this PaperSpec part: {part_name}.\n"
                f"Return one JSON object containing exactly these top-level fields: {', '.join(fields)}.\n"
                "Do not emit the other PaperSpec fields.\n\n"
                f"{PAPER_SPEC_ID_RULES}\n\n"
                f"{PAPER_SPEC_FIELD_CONTRACT}\n\n"
                f"{PAPER_SPEC_FEW_SHOT}\n\n"
                f"Expected partial shape:\n{json.dumps(part_shape, ensure_ascii=False)}\n\n"
                "Allowed Evidence IDs for this part:\n"
                + ("\n".join(f"- {item}" for item in part_evidence_ids) or "- none")
                + "\n\n"
                f"Paper title hint: {parsed.title or 'Untitled'}\n\n"
                f"Evidence context:\n{context}"
            )
        )
        part_payload = _invoke_paper_spec_part(
            model,
            system,
            user,
            part_name=part_name,
            progress=progress,
        )
        for field in fields:
            if field in part_payload:
                payload[field] = part_payload[field]
    if progress:
        progress("LLM: received and merged all PaperSpec parts")
    payload["id"] = stable_id("spec", parsed.paper_id)
    payload = normalize_paper_spec_payload(payload, allowed_evidence_ids=evidence_ids)
    return PaperSpec.model_validate(payload)


