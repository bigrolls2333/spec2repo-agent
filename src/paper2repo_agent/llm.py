def _normalize_component_io(value: object) -> list[str]:
    if isinstance(value, dict) and _looks_like_extracted_field(value):
        value = value.get("value")
    if isinstance(value, list):
        items = [_field_value(item) for item in value]
        return [item for item in items if item]
    text = _field_value(value)
    return [text] if text else []


def _normalize_component_hyperparameters(value: object) -> dict[str, dict[str, Any]]:
    if value is None:
        return {}
    if isinstance(value, dict) and _looks_like_extracted_field(value):
        return {"details": _normalize_extracted_field(value)}
    if not isinstance(value, dict):
        text = _field_value(value)
        return {"details": _normalize_extracted_field(text)} if text else {}

    normalized: dict[str, dict[str, Any]] = {}
    for key, raw in value.items():
        key_text = str(key or "").strip()
        if not key_text:
            continue
        normalized[key_text] = _normalize_extracted_field(raw)
    return normalized


