def _normalize_extracted_field(
    value: object,
    *,
    default_type: str | None = None,
) -> dict[str, Any]:
    if isinstance(value, dict):
        raw = value.get("value")
        notes = value.get("notes")
        if raw is None and notes not in (None, ""):
            raw = notes
        inferred_type = _infer_value_type(raw)
        value_type = str(
            value.get("value_type")
            or (
                default_type
                if raw in (None, "", []) and default_type is not None
                else inferred_type
            )
        )
        source_type = _normalize_literal(
            value.get("source_type", "inferred"),
            {"paper", "inferred", "default", "missing"},
            "inferred",
        )
        return {
            "value": raw,
            "value_type": value_type,
            "source_type": source_type,
            "evidence_ids": _collect_evidence_ids(value),
            "confidence": _safe_float(value.get("confidence"), 0.0),
            "notes": notes,
        }

    inferred = _infer_value_type(value)
    inferred_value_type = str(
        default_type if value in (None, "", []) and default_type is not None else inferred
    )
    return {
        "value": value,
        "value_type": inferred_value_type,
        "source_type": "inferred" if value not in (None, "", []) else "missing",
        "evidence_ids": [],
        "confidence": 0.0,
        "notes": None,
    }


def _looks_like_extracted_field(value: dict[str, Any]) -> bool:
    return any(
        key in value
        for key in {"value", "value_type", "source_type", "confidence", "notes", "evidence_ids"}
    )


def _infer_value_type(value: object) -> str:
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int) and not isinstance(value, bool):
        return "int"
    if isinstance(value, float):
        return "float"
    if isinstance(value, list):
        return "list"
    if isinstance(value, dict):
        return "dict"
    if value is None:
        return "unknown"
    return "str"


def _infer_equation_relevance(text: str) -> str:
    lowered = str(text or "").lower()
    if any(
        token in lowered for token in {"must", "core", "backprop", "training objective", "loss"}
    ):
        return "required"
    if any(token in lowered for token in {"not used", "omitted", "auxiliary"}):
        return "not_needed"
    return "helpful"


def _infer_metric_direction(text: str) -> str:
    lowered = str(text or "").lower()
    if any(
        token in lowered
        for token in {"loss", "error", "wer", "cer", "perplexity", "mae", "mse", "rmse"}
    ):
        return "lower_is_better"
    return "higher_is_better"


def _normalize_scalar_value(value: object) -> float | str:
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return float(value)
    text = _field_value(value)
    try:
        return float(text)
    except (TypeError, ValueError):
        return text or "unknown"


def _component_confidence(item: dict[str, Any]) -> float:
    if "confidence" in item:
        return _safe_float(item.get("confidence"), 0.0)
    for key in ("name", "component_type", "description"):
        nested = item.get(key)
        if isinstance(nested, dict) and "confidence" in nested:
            return _safe_float(nested.get("confidence"), 0.0)
    return 0.0


