"""Generate a Markdown test report from bench result JSONs.

Usage:
    python -m bench.report --runs runs --label-round r1 --out runs/BENCH_REPORT.r1.md

Reads each paper's result.json (+ the run-level bench_report.<label>.json when
present) and renders a resume-friendly report: success rates, verification
pass rates, P3 rollback activity agent trace breakdowns, timing, error list.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _load(p: Path) -> dict | None:
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return None


def _safe_get(d: dict, *keys, default=None):
    cur = d
    for k in keys:
        if not isinstance(cur, dict):
            return default
        cur = cur.get(k)
        if cur is None:
            return default
    return cur


def render(runs_dir: Path, label: str) -> str:
    bench_report = _load(runs_dir / f"bench_report.{label}.json") or {}
    summary = bench_report.get("summary", {})
    results = bench_report.get("results", [])

    # Fall back: gather per-paper result.json files directly
    if not results:
        for rd in sorted(runs_dir.iterdir()):
            if not rd.is_dir():
                continue
            rj = rd / "result.json"
            if not rj.exists():
                continue
            r = _load(rj)
            if r:
                results.append(r)

    lines: list[str] = []
    lines.append(f"# Paper2Repo 真实 LLM 批量实验报告（{label}）\n")
    lines.append(
        "> Generated by the batch benchmark; provider and model come from the local environment.\n"
    )

    # ── summary table ───────────────────────────────────────────────────────
    n = len(results)
    success = sum(1 for r in results if r.get("status") == "success")
    ver_pass = sum(1 for r in results if _safe_get(r, "metrics", "verification_passed") is True)
    rollback_runs = sum(1 for r in results if _safe_get(r, "metrics", "rollback_count"))
    plan_err = sum(1 for r in results if r.get("phase") == "plan" and r.get("status") == "error")
    exec_err = sum(1 for r in results if r.get("phase") == "execute" and r.get("status") == "error")

    lines.append("## 1. 总览\n")
    lines.append("| 指标 | 数值 |")
    lines.append("|---|---|")
    lines.append(f"| 论文总数 | {n} |")
    lines.append(f"| 全流程成功（execute done） | {success} |")
    lines.append(f"| 验证通过（verification_passed=True） | {ver_pass} |")
    lines.append(f"| 触发 P3 rollback 的论文数 | {rollback_runs} |")
    lines.append(f"| plan 阶段出错 | {plan_err} |")
    lines.append(f"| execute 阶段出错 | {exec_err} |")
    if summary:
        lines.append(f"| 超时数 | {summary.get('timeouts', 0)} |")
    lines.append("")

    # ── per-paper table ──────────────────────────────────────────────────────
    lines.append("## 2. 逐论文结果\n")
    lines.append(
        "| 论文 | 状态 | 验证通过 | plan(s) | exec(s) | 总(s) | agent traces | rollback | P3 判定 (C/F/I/U) | 备注 |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for r in results:
        m = r.get("metrics", {}) or {}
        pf = m.get("plan_feedback", {}) or {}
        pf_s = ""
        if pf:
            pf_s = f"{pf.get('confirmed', 0)}/{pf.get('falsified', 0)}/{pf.get('inconclusive', 0)}/{pf.get('untested', 0)}"
        name = (r.get("paper") or "")[:42]
        status = r.get("status") or "-"
        vp = "✓" if m.get("verification_passed") else "✗"
        pe = r.get("plan_elapsed_s") or r.get("plan_elapsed_s") or "-"
        ee = r.get("execute_elapsed_s") or "-"
        te = r.get("total_elapsed_s") or r.get("elapsed_s") or "-"
        atc = m.get("agent_trace_count", "-")
        rc = m.get("rollback_count", 0) or 0
        note = ""
        if r.get("status") == "error":
            note = (r.get("error") or "")[:60]
        lines.append(
            f"| {name} | {status} | {vp} | {pe} | {ee} | {te} | {atc} | {rc} | {pf_s} | {note} |"
        )
    lines.append("")

    # ── agent trace breakdown ───────────────────────────────────────────────
    lines.append("## 3. Agent trace 终态分布（ReAct 自停/硬停/升级 统计）\n")
    agg: dict[str, int] = {}
    py_total = 0
    for r in results:
        m = r.get("metrics", {}) or {}
        agg_local = m.get("agent_final_status_breakdown", {}) or {}
        for k, v in agg_local.items():
            agg[k] = agg.get(k, 0) + v
        py_total += m.get("generated_py_loc", 0) or 0
    if agg:
        lines.append("| final_status | 次数 |")
        lines.append("|---|---|")
        for k, v in sorted(agg.items(), key=lambda x: -x[1]):
            lines.append(f"| {k} | {v} |")
    else:
        lines.append("（无 agent trace 记录，可能 graceful fallback 到模板路径）")
    lines.append("")
    lines.append(f"**累计生成 Python 代码 LOC**：{py_total}\n")

    # ── errors ────────────────────────────────────────────────────────────────
    errs = [r for r in results if r.get("status") == "error" or r.get("timed_out")]
    if errs:
        lines.append("## 4. 失败 / 超时明细\n")
        for r in errs:
            lines.append(f"### {r.get('paper', '?')}")
            lines.append(
                f"- 阶段：`{r.get('phase', '?')}` | 超时：`{r.get('timed_out')}` | rc：`{r.get('rc', '-')}`"
            )
            if r.get("error"):
                lines.append(f"- 错误：`{r['error'][:300]}`")
            tb = r.get("traceback")
            if tb:
                lines.append("\n```\n" + tb + "\n```")
            lines.append("")

    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=Path, default=ROOT / "runs")
    ap.add_argument("--label-round", default="r1")
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()
    out = args.out or (args.runs / f"BENCH_REPORT.{args.label_round}.md")
    text = render(args.runs, args.label_round)
    out.write_text(text, encoding="utf-8")
    print(f"[report] wrote {out} ({len(text)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
